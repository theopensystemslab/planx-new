import type { Express } from "express";
import swaggerJSDoc from "swagger-jsdoc";
import swaggerUi from "swagger-ui-express";

const securitySchemes = {
  bearerAuth: {
    type: "http",
    scheme: "bearer",
    bearerFormat: "JWT",
  },
  fileAPIKeyAuth: {
    type: "apiKey",
    in: "header",
    name: "api-key",
    description:
      "API key granted to third-party integration partners to access files uploaded by users as part of their application",
  },
  hasuraAuth: {
    type: "apiKey",
    in: "header",
    name: "Authorization",
  },
  downloadTokenAuth: {
    type: "http",
    scheme: "bearer",
    bearerFormat: "uuid",
    description:
      "Short lived, single-use, token generated by the `/lps/download/token` endpoint",
  },
};

const parameters = {
  sessionId: {
    in: "path",
    name: "sessionId",
    schema: { type: "string" },
    required: true,
    description: "Session ID",
  },
  localAuthority: {
    in: "path",
    name: "localAuthority",
    schema: { type: "string" },
    required: true,
    description:
      "Name of the Local Authority, usually the same as PlanX `team`",
  },
  hasuraAuth: {
    name: "authorization",
    in: "header",
    description: "An authorisation header provided by Hasura",
    required: true,
    schema: { type: "string" },
  },
};

const schemas = {
  SessionPayload: {
    type: "object",
    properties: {
      payload: {
        type: "object",
        properties: {
          sessionId: {
            type: "string",
          },
        },
      },
    },
    example: {
      payload: {
        sessionId: "123",
      },
    },
  },
};

const responses = {
  ValidationError: {
    description:
      "Invalid request - the body, params, query or headers did not match the expected schema",
    content: {
      "application/json": {
        schema: {
          type: "object",
          required: ["error", "issues"],
          properties: {
            error: {
              type: "string",
              description: "Human-readable summary of every issue",
            },
            issues: {
              type: "array",
              description:
                "One entry per failed check, as reported by Zod. Further fields (e.g. `minimum`, `format`) depend on the `code`",
              items: {
                type: "object",
                required: ["code", "path", "message"],
                properties: {
                  code: { type: "string", example: "invalid_type" },
                  path: {
                    type: "array",
                    items: { type: ["string", "number"] },
                    example: ["body", "payload", "sessionId"],
                  },
                  message: { type: "string" },
                },
              },
            },
          },
        },
        example: {
          error:
            "✖ Invalid input: expected string, received undefined\n  → at body.payload.sessionId",
          issues: [
            {
              code: "invalid_type",
              expected: "string",
              path: ["body", "payload", "sessionId"],
              message: "Invalid input: expected string, received undefined",
            },
          ],
        },
      },
    },
  },
  Unauthorised: {
    description: "Unauthorised error",
    content: {
      "application/json": {
        schema: {
          type: "object",
          properties: {
            error: {
              type: "string",
              enum: ["Access denied"],
            },
          },
        },
      },
    },
  },
  SuccessMessage: {
    description: "Success message",
    content: {
      "application/json": {
        schema: {
          type: "object",
          properties: {
            message: {
              type: "string",
              example: "Success!",
            },
          },
        },
      },
    },
  },
  ErrorMessage: {
    description: "Error message",
    content: {
      "application/json": {
        schema: {
          type: "object",
          properties: {
            error: {
              type: "string",
              example: "Error!",
            },
          },
        },
      },
    },
  },
};

// Swagger documentation config
const options = {
  failOnErrors: true,
  definition: {
    openapi: "3.1.0",
    info: {
      title: "Plan✕ API",
      version: "0.1.0",
      description:
        "Plan✕ is a platform for creating and publishing digital planning services. Our REST API is built on Express and documented with Swagger.",
      license: {
        name: "MPL-2.0",
        url: "https://github.com/theopensystemslab/planx-new/blob/main/LICENSE.md",
      },
    },
    schemes: ["http", "https"],
    servers: [{ url: process.env.API_URL_EXT }],
    components: {
      securitySchemes,
      parameters,
      schemas,
      responses,
    },
  },
  apis: ["./**/docs.yaml"],
};

export const useSwaggerDocs = (app: Express) => {
  if (process.env.APP_ENVIRONMENT === "test") return;
  const swaggerSpec = swaggerJSDoc(options);
  app.use("/docs", swaggerUi.serve, swaggerUi.setup(swaggerSpec));
};
